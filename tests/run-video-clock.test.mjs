import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
let now = 100;
const context = vm.createContext({ performance: { now: () => now }, Date, Number, Math });
context.window = context;
vm.runInContext(fs.readFileSync(new URL('../run-video-delay.js', import.meta.url), 'utf8'), context);
vm.runInContext(fs.readFileSync(new URL('../run-video-clock.js', import.meta.url), 'utf8'), context);
const listeners = {};
const cap = { requestedAudioDelaySeconds: 0.15, startedAt: Date.now() };
context.initRunVideoClock(cap, { addEventListener: (event, fn) => listeners[event] = fn });
now = 450; listeners.start({ timeStamp: 400 });
now = 5900;
context.markRunVideoMusicStart(cap, { muted: true, paused: false }, 0);
assert.equal(cap.audioStartedAt, null, 'silent priming must not latch the music start');
context.markRunVideoMusicStart(cap, { muted: false, paused: false }, 0.3);
assert.equal(cap.recordingAudioDelaySeconds, 5.2, 'remove both recorder startup and music notification delay');
now = 10000; context.markRunVideoMusicStart(cap, { muted: false, paused: false }, 1);
assert.equal(cap.recordingAudioDelaySeconds, 5.2, 'a resumed play cannot replace the original anchor');
cap.captureClock.stopped = 15400; now = 16600;
const fields = context.finishRunVideoClock(cap);
assert.equal(fields.duration, 15, 'file flush latency is not footage');
assert.equal(fields.estimatedAudioDelaySeconds, 5.2, 'manual preference does not move the estimated centre');
assert.equal(fields.syncAudioDelaySeconds, 5.35);
assert.equal(fields.captureTiming.recorderStartupMs, 300);
const fallback = { requestedAudioDelaySeconds: 0 };
context.initRunVideoClock(fallback, { addEventListener() {} });
now += 500; context.markRunVideoMusicStart(fallback, { paused: false }, 0.1);
assert.equal(context.finishRunVideoClock(fallback).captureTiming.source, 'recorder-request-fallback');
assert.equal(fallback.recordingAudioDelaySeconds, 0.4);
console.log('Capture clock regression PASS (priming, startup, media advance, repeated play, stop, fallback)');
